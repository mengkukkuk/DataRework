"""Damage Report as a PDF: which serials are flagged damaged right now.

The rows come from db.list_damaged (staging_serial_data); this module only lays
them out. QPdfWriter + QTextDocument is used instead of a PDF library so there is
nothing new to ship, and Qt's own text shaping draws Thai correctly with the same
font the program uses. The table header repeats on every page (<thead>).
"""
import datetime
import html
import os

from PySide6.QtCore import QMarginsF, QRectF, QSizeF, Qt
from PySide6.QtGui import QFont, QPageLayout, QPageSize, QPainter, QPdfWriter, QTextDocument

from i18n import tr
from typography import ui_font

STAMP = "%Y-%m-%d %H:%M"

# Columns the operator can leave out of the PDF: (row key, heading). The serial
# and the damage time are what the report is about, so they always print.
OPTIONAL_COLUMNS = (("level", "Type"), ("roll_no", "Roll no"), ("box_no", "Box no"))


def default_filename(now=None):
    now = now or datetime.datetime.now()
    return f"damage_report_{now:%Y%m%d_%H%M%S}.pdf"


def default_folder():
    """DAMAGE_REPORT_DIR from .env, else the user's Documents folder."""
    configured = os.environ.get("DAMAGE_REPORT_DIR", "").strip()
    if configured:
        return os.path.expandvars(os.path.expanduser(configured))
    documents = os.path.join(os.path.expanduser("~"), "Documents")
    return documents if os.path.isdir(documents) else os.path.expanduser("~")


def _fmt(value):
    return value.astimezone().strftime(STAMP) if value else ""


def describe_range(start, end):
    if start is None and end is None:
        return str(tr("All time"))
    return str(tr("{p0} to {p1}",
                  p0=start.strftime(STAMP) if start else "…",
                  p1=end.strftime(STAMP) if end else "…"))


def build_html(rows, start=None, end=None, generated_by="", vm_id="", now=None, columns=None):
    """`columns`: the OPTIONAL_COLUMNS keys to include; None means all of them."""
    esc = lambda value: html.escape("" if value is None else str(value))
    now = now or datetime.datetime.now()
    optional = [(key, label) for key, label in OPTIONAL_COLUMNS
                if columns is None or key in columns]
    labels = [tr("#"), tr("Serial")] + [tr(label) for _, label in optional]         + [tr("Damaged at"), tr("Last used by")]

    meta = [
        (tr("Time range"), describe_range(start, end)),
        (tr("Generated"), now.strftime(STAMP)),
    ]
    if generated_by:
        meta.append((tr("Generated by"), generated_by))
    if vm_id:
        meta.append((tr("VM"), vm_id))
    meta.append((tr("Damaged serials"), len(rows)))

    head = "".join(
        f'<th align="left" style="background-color:#e6ecf2;">{esc(label)}</th>'
        for label in labels)
    body = "".join(
        "<tr>" + "".join(f"<td>{esc(cell)}</td>" for cell in (
            index, row["serial_no"], *(row[key] for key, _ in optional),
            _fmt(row["damaged_at"]) or tr("Not recorded"), row["last_user"])) + "</tr>"
        for index, row in enumerate(rows, start=1))
    if not rows:
        body = (f'<tr><td colspan="{len(labels)}">'
                f'{esc(tr("No damaged serials in this range."))}</td></tr>')
    return (
        f"<h2>{esc(tr('Damage report'))}</h2>"
        "<table cellspacing='0' cellpadding='2'>"
        + "".join(f"<tr><td><b>{esc(k)}</b></td><td>{esc(v)}</td></tr>" for k, v in meta)
        + "</table><br>"
        '<table border="1" cellspacing="0" cellpadding="4" width="100%" '
        'style="border-collapse:collapse;">'
        f"<thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"
    )


FOOTER_H = 24  # layout units reserved under each page for "Page i / n"
SCREEN_DPI = 96.0  # QTextDocument lays text out in these units; we scale up to the PDF


def export_pdf(path, rows, start=None, end=None, generated_by="", vm_id="", now=None,
               columns=None):
    """Write the report to `path`. Raises OSError if the file can't be created."""
    folder = os.path.dirname(os.path.abspath(path))
    if not os.path.isdir(folder):
        raise FileNotFoundError(f"Folder does not exist: {folder}")
    writer = QPdfWriter(path)
    writer.setPageLayout(QPageLayout(
        QPageSize(QPageSize.A4), QPageLayout.Portrait, QMarginsF(15, 15, 15, 15),
        QPageLayout.Millimeter))
    writer.setTitle(str(tr("Damage report")))
    doc = QTextDocument()
    font = ui_font()
    font.setPointSize(9)  # print size; ui_font is pixel-sized for the screen
    doc.setDefaultFont(font)
    doc.setHtml(build_html(rows, start, end, generated_by, vm_id, now, columns))

    # Paginate by hand rather than doc.print_(): print_ ignores our margins
    # (they come out ~20 mm too wide) and can't draw "Page 1 / 3". The document is
    # laid out in 96-dpi units, one page rect at a time, and the painter scales
    # that up to the writer's resolution.
    scale = writer.logicalDpiX() / SCREEN_DPI
    page_w, page_h = writer.width() / scale, writer.height() / scale
    # The writer clips to the page minus margins, so the footer needs a strip of
    # its own inside that area; the document gets the rest.
    body_h = page_h - FOOTER_H
    doc.setPageSize(QSizeF(page_w, body_h))
    pages = max(doc.pageCount(), 1)
    painter = QPainter(writer)
    painter.scale(scale, scale)
    footer_font = QFont(font)
    footer_font.setPixelSize(11)  # layout units: the painter is already scaled
    for page in range(pages):
        if page:
            writer.newPage()
        painter.save()
        painter.translate(0, -page * body_h)
        doc.drawContents(painter, QRectF(0, page * body_h, page_w, body_h))
        painter.restore()
        painter.setFont(footer_font)
        painter.drawText(QRectF(0, body_h, page_w, FOOTER_H), Qt.AlignRight | Qt.AlignVCenter,
                         str(tr("Page {p0} / {p1}", p0=page + 1, p1=pages)))
    painter.end()
    del painter, doc, writer  # the PDF is only complete once the writer is destroyed
    # QPdfWriter only reports failure by not producing a file.
    if not os.path.isfile(path):
        raise OSError(f"Could not write {path}")
    return path
